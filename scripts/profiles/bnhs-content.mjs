export const HISTORY = `## How it began (2004)

It was in **2004** when Mr. Elias B. Aladano, Secondary School Head Teacher III, initiated the establishment of Bolo Norte High School as an **Extension High School of Sipocot National High School**. The effort had the full support of the Barangay Council headed by Barangay Captain Marianito P. Tatel, Sr., and of the Sipocot National High School Principal, Mrs. Leonor B. Emata.

## The pioneer teachers

The first teachers were part-time teachers from Sipocot National High School:

- **Mr. Dalmacio C. Untalan, Jr.** – class adviser of the pioneer class; English, Values Education and Araling Panlipunan
- **Ms. Amparo Capin** – Filipino
- **Mrs. Cynthia S. Candelaria** – Mathematics
- **Mr. Edgar F. Alcantara** – Science and Technology
- **Mr. Elias B. Aladano** – TLE and MAPEH, who also served as school head

The first batch had **58 enrollees**.

## Growth (2005 onward)

In **2005**, because of the rapid increase in enrollment, two temporary PTA classrooms were built through the efforts of PTCA President Mr. Teopilo C. Amante. Locally assisted teachers funded by the PTCA joined the school that year: Jecile C. Gatpadan (June 6), Agustin Cesar S. Camba (June 8), Francia M. Maravillo (June 11), Ricardo V. Castillo (June 17), Myla F. Camba (June 18), Lilibeth C. Deyto (September 5) and Maribel B. Calayo (November 7).

Enrollment kept rising every year, so more temporary PTA classrooms were added to accommodate all learners. In the following years the Department of Education constructed new school buildings.

## Bolo Norte National High School

The school that began as an extension of Sipocot National High School is today **Bolo Norte National High School**, identified in DepEd records by School ID **309743**. The year **2007** appears on the official school seal. It now serves learners in both Junior High School and Senior High School.

## The school and its community

According to the school's 2016 profile, the campus sits along the national highway in Barangay Bolo Norte, about 9.5 kilometers from the Sipocot town proper. The 10,000-square-meter site was formerly used as a dumping site by a construction company that was asphalting the national highway between Camarines Sur and Camarines Norte, which explains its rocky and sandy soil. Learners come from six feeder barangays: Bolo Norte, Bolo Sur, Calagbangan, Yabu, Salanda and Alteza. The community is peaceful and, because of its high location, free from flooding.

## Senior High School and work immersion

With the K to 12 program the school added Senior High School with a Technical-Vocational-Livelihood (TVL) track. Grade 12 learners in TVL – Electrical Installation and Maintenance (EIM) and Tailoring take part in a school-based work immersion; the 2021 run was held from May 24 to June 4, 2021 with health and safety protocols observed.

## Our vision for the future

Bolo Norte National High School aspires to be a developed school that produces well-rounded individuals coping with technological changes.`;

